def punto_ruta(frac, ruta=RUTA_PLATA):
    P = poli(ruta)
    seg = np.hypot(*np.diff(P, axis=0).T)
    d = np.concatenate([[0], np.cumsum(seg)])
    L = d[-1] * min(max(frac, 0.0), 1.0)
    return np.array([np.interp(L, d, P[:, 0]), np.interp(L, d, P[:, 1])])
