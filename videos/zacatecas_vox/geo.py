K = 60.0
LON0, LAT0 = -102.57, 22.77          # Zacatecas
CX = math.cos(math.radians(24))


def xy(lon, lat):
    return ((lon - LON0) * K * CX, -(lat - LAT0) * K)


def poli(ll):
    return np.array([xy(a, b) for a, b in ll])


